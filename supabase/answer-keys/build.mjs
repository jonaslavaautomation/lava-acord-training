// Builds supabase/migrations/20261111120000_auto_answer_keys.sql from rules.mjs.
//   node supabase/answer-keys/build.mjs                         -> write the migration
//   node supabase/answer-keys/build.mjs --check 125=fields.tsv  -> show which PDF field each rule picks
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { RULES } from './rules.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const nameRx = (n) => (n ? `(^|\\.)${n}$` : null);
const kindOf = (r) => r.kind ?? 'text';

const rows = Object.entries(RULES).flatMap(([moduleId, rules]) => {
  const keys = new Set();
  return rules.map((r, i) => {
    if (keys.has(r.key)) throw new Error(`Duplicate rule key ${moduleId}/${r.key}`);
    keys.add(r.key);
    return {
      module_id: moduleId, rule_key: r.key, label: r.label, name_rx: nameRx(r.n), tip_rx: r.tip ?? null, nth: r.nth ?? 1,
      field_kind: kindOf(r), expected_value: r.v ?? '', match_type: r.match, points: r.pts, required: !!r.req,
      missing_rule: r.miss ?? 'penalize', feedback_hint: r.hint ?? null, sort_order: i + 1,
    };
  });
});

// ---------------------------------------------------------------- --check: simulate the SQL matcher on a field dump
const checks = process.argv.slice(2).filter((a) => a.includes('='));
if (process.argv.includes('--check')) {
  for (const spec of checks) {
    const [moduleId, file] = spec.split('=');
    const fields = fs.readFileSync(file, 'utf8').split('\n').filter(Boolean).map((l, idx) => {
      const [type, page, name, tip] = l.split('\t');
      return { type, page: Number(page), name, tip: tip ?? '', idx };
    });
    const claimed = new Set();
    let ok = 0;
    const bad = [];
    for (const r of rows.filter((x) => x.module_id === moduleId)) {
      const nrx = r.name_rx && new RegExp(r.name_rx, 'i');
      const trx = r.tip_rx && new RegExp(r.tip_rx, 'i');
      const cands = fields
        .filter((f) => (r.field_kind === 'checkbox' ? f.type === 'checkbox' : ['text', 'date', 'dropdown'].includes(f.type)))
        .map((f) => ({ ...f, byName: !!nrx && nrx.test(f.name.replace(/\[\d+\]/g, '')) }))
        .filter((f) => f.byName || (trx && trx.test(f.tip)))
        .sort((a, b) => Number(b.byName) - Number(a.byName) || a.page - b.page || a.idx - b.idx);
      const pick = cands[r.nth - 1];
      if (!pick || claimed.has(pick.name)) { bad.push(r.label); continue; }
      claimed.add(pick.name);
      ok++;
      console.log(`  ${moduleId} ${r.rule_key.padEnd(16)} -> ${pick.name.replace(/\[0\]/g, '')}  (${cands.length} candidate${cands.length === 1 ? '' : 's'})`);
    }
    console.log(`ACORD ${moduleId}: ${ok}/${ok + bad.length} rules matched${bad.length ? `; NOT FOUND: ${bad.join(', ')}` : ''}\n`);
  }
  process.exit(0);
}

// ---------------------------------------------------------------- SQL
const q = (v) => (v === null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const values = rows.map((r) =>
  `  (${[q(r.module_id), q(r.rule_key), q(r.label), q(r.name_rx), q(r.tip_rx), r.nth, q(r.field_kind), q(r.expected_value),
    q(r.match_type), r.points, r.required, q(r.missing_rule), q(r.feedback_hint), r.sort_order].join(', ')})`).join(',\n');

const sql = `/*
# Automatic answer keys

Generated by supabase/answer-keys/build.mjs from supabase/answer-keys/rules.mjs — edit the rules there, not here.

When a trainer uploads a fillable ACORD PDF, \`auto_configure_answer_key\` finds the PDF field for every scenario detail
(by the ACORD AcroForm field name, or by the ACORD tooltip for editions with generic names like "Text31") and writes
the expected answer into \`pdf_field_mappings\`, which the existing server-side grader uses. No manual mapping needed.

- Rules live in the private schema; students can never read them.
- Answers a trainer typed by hand are kept (pass p_overwrite => true to replace them).
- Running this migration also configures every PDF that is already uploaded.
*/

CREATE TABLE IF NOT EXISTS lava_private.answer_key_rules (
  module_id text NOT NULL REFERENCES public.acord_modules(id),
  rule_key text NOT NULL,
  label text NOT NULL,
  name_rx text,
  tip_rx text,
  nth integer NOT NULL DEFAULT 1,
  field_kind text NOT NULL DEFAULT 'text' CHECK (field_kind IN ('text', 'checkbox')),
  expected_value text NOT NULL DEFAULT '',
  match_type text NOT NULL CHECK (match_type IN ('exact', 'contains', 'any-of', 'keywords', 'present')),
  points integer NOT NULL DEFAULT 1,
  required boolean NOT NULL DEFAULT false,
  missing_rule text NOT NULL DEFAULT 'penalize' CHECK (missing_rule IN ('penalize', 'expect_blank', 'optional')),
  feedback_hint text,
  sort_order integer NOT NULL DEFAULT 0,
  PRIMARY KEY (module_id, rule_key)
);
REVOKE ALL ON lava_private.answer_key_rules FROM PUBLIC, anon, authenticated;

DELETE FROM lava_private.answer_key_rules;
INSERT INTO lava_private.answer_key_rules
  (module_id, rule_key, label, name_rx, tip_rx, nth, field_kind, expected_value, match_type, points, required, missing_rule, feedback_hint, sort_order)
VALUES
${values};

CREATE OR REPLACE FUNCTION public.auto_configure_answer_key(p_material_id uuid, p_overwrite boolean DEFAULT false)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_mat public.training_materials;
  r lava_private.answer_key_rules;
  v_field text;
  v_type text;
  v_page integer;
  v_existing public.pdf_field_mappings;
  v_claimed text[] := '{}';
  v_matched integer := 0;
  v_kept integer := 0;
  v_total integer := 0;
  v_not_found jsonb := '[]'::jsonb;
BEGIN
  -- Staff only. (auth.uid() is NULL only for the SQL editor / migrations; anon has no EXECUTE grant.)
  IF auth.uid() IS NOT NULL AND NOT public.is_staff() THEN RAISE EXCEPTION 'FORBIDDEN'; END IF;

  SELECT * INTO v_mat FROM public.training_materials WHERE id = p_material_id AND material_type = 'pdf';
  IF v_mat.id IS NULL THEN RAISE EXCEPTION 'MATERIAL_NOT_FOUND'; END IF;

  FOR r IN SELECT * FROM lava_private.answer_key_rules WHERE module_id = v_mat.module_id ORDER BY sort_order LOOP
    v_total := v_total + 1;

    SELECT c.field_name, c.field_type, c.page_number INTO v_field, v_type, v_page
    FROM (
      SELECT x.*, (r.name_rx IS NOT NULL AND regexp_replace(x.field_name, '\\[\\d+\\]', '', 'g') ~* r.name_rx) AS by_name
      FROM public.pdf_form_fields x
      WHERE x.material_id = p_material_id
        AND CASE WHEN r.field_kind = 'checkbox' THEN x.field_type = 'checkbox'
                 ELSE x.field_type IN ('text', 'date', 'dropdown') END
    ) c
    WHERE c.by_name OR (r.tip_rx IS NOT NULL AND coalesce(c.tooltip, '') ~* r.tip_rx)
    ORDER BY c.by_name DESC, c.page_number, coalesce(c.rect[4], 0) DESC, coalesce(c.rect[1], 0), c.field_name
    OFFSET greatest(r.nth, 1) - 1 LIMIT 1;

    IF NOT FOUND OR v_field = ANY (v_claimed) THEN
      v_not_found := v_not_found || to_jsonb(r.label);
      CONTINUE;
    END IF;
    v_claimed := v_claimed || v_field;

    SELECT * INTO v_existing FROM public.pdf_field_mappings WHERE material_id = p_material_id AND pdf_field_name = v_field;
    IF NOT p_overwrite AND v_existing.id IS NOT NULL
       AND coalesce(v_existing.scenario_fact_key, '') NOT LIKE 'auto:%'
       AND (coalesce(v_existing.expected_value, '') <> '' OR v_existing.match_type = 'present' OR v_existing.missing_rule = 'expect_blank') THEN
      v_kept := v_kept + 1;   -- a trainer configured this field by hand; keep it
      CONTINUE;
    END IF;

    INSERT INTO public.pdf_field_mappings (module_id, material_id, pdf_field_name, pdf_field_type, scenario_label, scenario_fact_key,
        expected_value, match_type, points, required, missing_rule, feedback_hint, is_scored, page_number, updated_at)
    VALUES (v_mat.module_id, p_material_id, v_field, v_type, r.label, 'auto:' || r.rule_key,
        r.expected_value, r.match_type, r.points, r.required, r.missing_rule, r.feedback_hint, true, v_page, now())
    ON CONFLICT (material_id, pdf_field_name) DO UPDATE SET
      scenario_label = EXCLUDED.scenario_label, scenario_fact_key = EXCLUDED.scenario_fact_key,
      expected_value = EXCLUDED.expected_value, match_type = EXCLUDED.match_type, points = EXCLUDED.points,
      required = EXCLUDED.required, missing_rule = EXCLUDED.missing_rule, feedback_hint = EXCLUDED.feedback_hint,
      is_scored = true, updated_at = now();
    v_matched := v_matched + 1;
  END LOOP;

  -- Clear stale automatic answers on fields no rule points to any more.
  UPDATE public.pdf_field_mappings
     SET expected_value = '', scenario_fact_key = NULL, required = false, feedback_hint = NULL, updated_at = now()
   WHERE material_id = p_material_id AND scenario_fact_key LIKE 'auto:%' AND NOT (pdf_field_name = ANY (v_claimed));

  RETURN jsonb_build_object('matched', v_matched, 'kept_manual', v_kept, 'total_rules', v_total, 'not_found', v_not_found);
END $$;

REVOKE EXECUTE ON FUNCTION public.auto_configure_answer_key(uuid, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.auto_configure_answer_key(uuid, boolean) TO authenticated;

-- Configure every fillable PDF that is already uploaded.
SELECT t.module_id, t.file_name, public.auto_configure_answer_key(t.id) AS result
FROM public.training_materials t
WHERE t.material_type = 'pdf' AND t.is_current
ORDER BY t.module_id;
`;

const out = path.join(here, '..', 'migrations', '20261111120000_auto_answer_keys.sql');
fs.writeFileSync(out, sql);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${rows.length} rules)`);
