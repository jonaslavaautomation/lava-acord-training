//   node supabase/knowledge-checks/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PASS_SCORE, QUESTIONS } from './questions.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const migrations = path.join(here, '..', 'migrations');

// ---- validate
for (const [mod, qs] of Object.entries(QUESTIONS)) {
  if (qs.length < 15) throw new Error(`ACORD ${mod} has ${qs.length} questions; at least 15 are required`);
  const keys = new Set();
  for (const q of qs) {
    if (keys.has(q.key)) throw new Error(`Duplicate key ${mod}/${q.key}`);
    keys.add(q.key);
    if (!Array.isArray(q.options) || q.options.length < 2 || q.options.length > 6) throw new Error(`${mod}/${q.key}: 2-6 options required`);
    if (!Number.isInteger(q.answer) || q.answer < 0 || q.answer >= q.options.length) throw new Error(`${mod}/${q.key}: answer out of range`);
    if (new Set(q.options).size !== q.options.length) throw new Error(`${mod}/${q.key}: duplicate options`);
  }
}

// ---- start_assessment: reuse the deployed definition and add the knowledge-check gate
const secure = fs.readFileSync(path.join(migrations, '20261111090000_secure_materials_pdf_assessments.sql'), 'utf8');
const start = secure.indexOf('CREATE OR REPLACE FUNCTION public.start_assessment');
const end = secure.indexOf('END $$;', start) + 'END $$;'.length;
let startFn = secure.slice(start, end);
const anchor = "  SELECT * INTO v_pdf FROM public.training_materials WHERE module_id = p_module_id AND material_type = 'pdf' AND is_current;";
if (start < 0 || !startFn.includes(anchor)) throw new Error('Could not locate start_assessment in the secure migration');
startFn = startFn.replace(anchor, `  -- Knowledge Check gate: the module's quiz must be passed before the PDF assessment.
  IF EXISTS (SELECT 1 FROM public.knowledge_check_questions WHERE module_id = p_module_id AND is_active)
     AND NOT EXISTS (SELECT 1 FROM public.knowledge_check_attempts WHERE user_id = v_uid AND module_id = p_module_id AND passed) THEN
    RAISE EXCEPTION 'KNOWLEDGE_CHECK_NOT_PASSED';
  END IF;

${anchor}`);

// ---- seed
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const values = Object.entries(QUESTIONS).flatMap(([mod, qs]) => qs.map((x, i) =>
  `  (${[q(mod), q(x.key), i + 1, q(x.q), `${q(JSON.stringify(x.options))}::jsonb`, x.answer, q(x.why ?? '')].join(', ')})`)).join(',\n');
const keyList = Object.entries(QUESTIONS).flatMap(([mod, qs]) => qs.map((x) => `(${q(mod)}, ${q(x.key)})`)).join(', ');

const sql = `/*
# Knowledge Checks (15+ questions per ACORD form)

Generated by supabase/knowledge-checks/build.mjs from supabase/knowledge-checks/questions.mjs — edit the questions there.

Flow per module:  training video (95% watched, server-verified)  ->  Knowledge Check (pass ${PASS_SCORE}%)  ->  PDF assessment.

- Questions and correct answers are staff-only; students receive questions WITHOUT answers via get_knowledge_check().
- submit_knowledge_check() grades on the server. Failed attempts only reveal WHICH questions were wrong;
  the correct answers and explanations are shown once the student passes.
- start_assessment() now refuses to start until the module's Knowledge Check is passed.
*/

-- ============================================================ tables
CREATE TABLE IF NOT EXISTS public.knowledge_check_questions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  module_id text NOT NULL REFERENCES public.acord_modules(id),
  question_key text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  prompt text NOT NULL,
  options jsonb NOT NULL CHECK (jsonb_typeof(options) = 'array' AND jsonb_array_length(options) BETWEEN 2 AND 6),
  correct_index integer NOT NULL CHECK (correct_index >= 0),
  explanation text NOT NULL DEFAULT '',
  is_active boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (module_id, question_key),
  CHECK (correct_index < jsonb_array_length(options))
);
ALTER TABLE public.knowledge_check_questions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.knowledge_check_questions FROM anon;
DROP POLICY IF EXISTS "kc_questions_staff_all" ON public.knowledge_check_questions;
CREATE POLICY "kc_questions_staff_all" ON public.knowledge_check_questions FOR ALL TO authenticated
  USING (public.is_staff()) WITH CHECK (public.is_staff());
GRANT SELECT, INSERT, UPDATE, DELETE ON public.knowledge_check_questions TO authenticated;

CREATE TABLE IF NOT EXISTS public.knowledge_check_attempts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  module_id text NOT NULL REFERENCES public.acord_modules(id),
  score integer NOT NULL,
  correct integer NOT NULL,
  total integer NOT NULL,
  passed boolean NOT NULL,
  answers jsonb NOT NULL DEFAULT '{}'::jsonb,
  results jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_kc_attempts_user_module ON public.knowledge_check_attempts(user_id, module_id, created_at DESC);
ALTER TABLE public.knowledge_check_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.knowledge_check_attempts FROM anon;
DROP POLICY IF EXISTS "kc_attempts_select" ON public.knowledge_check_attempts;
CREATE POLICY "kc_attempts_select" ON public.knowledge_check_attempts FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR public.is_staff());
DROP POLICY IF EXISTS "kc_attempts_staff_delete" ON public.knowledge_check_attempts;
CREATE POLICY "kc_attempts_staff_delete" ON public.knowledge_check_attempts FOR DELETE TO authenticated
  USING (public.is_staff());
GRANT SELECT, DELETE ON public.knowledge_check_attempts TO authenticated;
-- Inserts only happen through submit_knowledge_check() (SECURITY DEFINER).

-- ============================================================ question bank
INSERT INTO public.knowledge_check_questions (module_id, question_key, sort_order, prompt, options, correct_index, explanation)
VALUES
${values}
ON CONFLICT (module_id, question_key) DO UPDATE SET
  sort_order = EXCLUDED.sort_order, prompt = EXCLUDED.prompt, options = EXCLUDED.options,
  correct_index = EXCLUDED.correct_index, explanation = EXCLUDED.explanation, is_active = true, updated_at = now();

-- Questions removed from questions.mjs are retired (kept for attempt history).
UPDATE public.knowledge_check_questions SET is_active = false, updated_at = now()
WHERE (module_id, question_key) NOT IN (${keyList});

-- ============================================================ helpers
CREATE OR REPLACE FUNCTION lava_private.module_videos_complete(p_uid uuid, p_module_id text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.training_materials WHERE module_id = p_module_id AND material_type = 'video' AND is_current)
     AND NOT EXISTS (
       SELECT 1 FROM public.training_materials t
       LEFT JOIN public.video_progress vp ON vp.asset_key = t.asset_key AND vp.user_id = p_uid
       WHERE t.module_id = p_module_id AND t.material_type = 'video' AND t.is_current AND t.is_required
         AND coalesce(vp.completed, false) = false)
$$;
REVOKE EXECUTE ON FUNCTION lava_private.module_videos_complete(uuid, text) FROM PUBLIC, anon, authenticated;

-- ============================================================ student RPCs
-- Status + questions (without answers). Questions are only returned once the video is complete and the check is not yet passed.
CREATE OR REPLACE FUNCTION public.get_knowledge_check(p_module_id text) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_count integer;
  v_video boolean;
  v_passed boolean;
  v_best integer;
  v_attempts integer;
  v_last jsonb;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'NOT_AUTHENTICATED'; END IF;
  SELECT count(*) INTO v_count FROM public.knowledge_check_questions WHERE module_id = p_module_id AND is_active;
  v_video := lava_private.module_videos_complete(v_uid, p_module_id);
  SELECT coalesce(bool_or(passed), false), max(score), count(*) INTO v_passed, v_best, v_attempts
    FROM public.knowledge_check_attempts WHERE user_id = v_uid AND module_id = p_module_id;
  SELECT jsonb_build_object('score', score, 'correct', correct, 'total', total, 'passed', passed, 'created_at', created_at,
           'results', CASE WHEN passed THEN results ELSE '[]'::jsonb END)
    INTO v_last FROM public.knowledge_check_attempts
    WHERE user_id = v_uid AND module_id = p_module_id ORDER BY passed DESC, created_at DESC LIMIT 1;

  RETURN jsonb_build_object(
    'question_count', v_count,
    'pass_score', ${PASS_SCORE},
    'video_complete', v_video,
    'passed', v_passed,
    'best_score', v_best,
    'attempts', v_attempts,
    'last_attempt', v_last,
    'questions', CASE WHEN v_video AND NOT v_passed AND v_count > 0 THEN (
      SELECT jsonb_agg(jsonb_build_object('id', id, 'prompt', prompt, 'options', options) ORDER BY sort_order)
      FROM public.knowledge_check_questions WHERE module_id = p_module_id AND is_active) ELSE '[]'::jsonb END);
END $$;

-- p_answers: { "<question id>": <chosen option index>, ... }
CREATE OR REPLACE FUNCTION public.submit_knowledge_check(p_module_id text, p_answers jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_uid uuid := auth.uid();
  qrow record;
  v_given integer;
  v_ok boolean;
  v_correct integer := 0;
  v_total integer := 0;
  v_score integer;
  v_passed boolean;
  v_results jsonb := '[]'::jsonb;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'NOT_AUTHENTICATED'; END IF;
  IF p_answers IS NULL OR jsonb_typeof(p_answers) <> 'object' THEN RAISE EXCEPTION 'INVALID_VALUES'; END IF;
  IF NOT lava_private.module_videos_complete(v_uid, p_module_id) THEN RAISE EXCEPTION 'VIDEO_INCOMPLETE'; END IF;
  IF EXISTS (SELECT 1 FROM public.knowledge_check_attempts WHERE user_id = v_uid AND module_id = p_module_id AND passed) THEN
    RAISE EXCEPTION 'KNOWLEDGE_CHECK_ALREADY_PASSED';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('kc:' || v_uid::text || ':' || p_module_id));

  FOR qrow IN SELECT * FROM public.knowledge_check_questions WHERE module_id = p_module_id AND is_active ORDER BY sort_order LOOP
    v_total := v_total + 1;
    v_given := CASE WHEN jsonb_typeof(p_answers -> qrow.id::text) = 'number' THEN (p_answers ->> qrow.id::text)::integer END;
    v_ok := v_given IS NOT NULL AND v_given = qrow.correct_index;
    IF v_ok THEN v_correct := v_correct + 1; END IF;
    v_results := v_results || jsonb_build_array(jsonb_build_object(
      'id', qrow.id, 'prompt', qrow.prompt, 'options', qrow.options, 'given', v_given, 'correct', v_ok,
      'correct_index', qrow.correct_index, 'explanation', qrow.explanation));
  END LOOP;
  IF v_total = 0 THEN RAISE EXCEPTION 'KNOWLEDGE_CHECK_NOT_FOUND'; END IF;

  v_score := round(v_correct * 100.0 / v_total);
  v_passed := v_score >= ${PASS_SCORE};
  INSERT INTO public.knowledge_check_attempts (user_id, module_id, score, correct, total, passed, answers, results)
  VALUES (v_uid, p_module_id, v_score, v_correct, v_total, v_passed, p_answers, v_results);

  RETURN jsonb_build_object('score', v_score, 'correct', v_correct, 'total', v_total, 'passed', v_passed, 'pass_score', ${PASS_SCORE},
    -- Before passing, only reveal which questions were wrong — not the right answers.
    'results', CASE WHEN v_passed THEN v_results ELSE (
      SELECT coalesce(jsonb_agg(jsonb_build_object('id', r->'id', 'prompt', r->'prompt', 'given', r->'given', 'correct', r->'correct')), '[]'::jsonb)
      FROM jsonb_array_elements(v_results) r) END);
END $$;

-- Staff: let a student retake a passed check (e.g. after the video or questions change).
CREATE OR REPLACE FUNCTION public.staff_reset_knowledge_check(p_user_id uuid, p_module_id text) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE n integer;
BEGIN
  IF NOT public.is_staff() THEN RAISE EXCEPTION 'FORBIDDEN'; END IF;
  DELETE FROM public.knowledge_check_attempts WHERE user_id = p_user_id AND module_id = p_module_id;
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$;

-- ============================================================ assessment gate
${startFn}

REVOKE EXECUTE ON FUNCTION public.get_knowledge_check(text), public.submit_knowledge_check(text, jsonb),
  public.staff_reset_knowledge_check(uuid, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_knowledge_check(text), public.submit_knowledge_check(text, jsonb),
  public.staff_reset_knowledge_check(uuid, text), public.start_assessment(text) TO authenticated;
`;

