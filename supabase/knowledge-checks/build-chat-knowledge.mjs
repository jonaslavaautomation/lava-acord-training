// Packs the training-video transcripts into api/_acord-knowledge.ts for the ACORD Assistant chatbot.
//   node supabase/knowledge-checks/build-chat-knowledge.mjs
// Only the transcripts go in: the assessment scenarios and answer keys are deliberately left out.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, 'transcripts');
const TITLES = {
  125: 'ACORD 125 — Commercial Insurance Application',
  126: 'ACORD 126 — Commercial General Liability Section',
  127: 'ACORD 127 — Business Auto Section',
  130: 'ACORD 130 — Workers Compensation Application',
  140: 'ACORD 140 — Property Section',
  27: 'ACORD 27 — Evidence of Property Insurance',
};

// A form whose video hasn't been transcribed yet (no transcripts/acord-<id>.txt) is skipped.
const missing = [];
const parts = Object.entries(TITLES).flatMap(([id, title]) => {
  const file = path.join(dir, `acord-${id}.txt`);
  if (!fs.existsSync(file)) { missing.push(`ACORD ${id}`); return []; }
  const body = fs.readFileSync(file, 'utf8')
    .split('\n').filter((l) => l.trim() && !l.startsWith('#')).join('\n');
  return [`<training_video form="ACORD ${id}" title="${title}">\n${body}\n</training_video>`];
});

// Written process guides (SOPs) go in too: guides/acord-<id>-*.txt
const guideDir = path.join(here, 'guides');
if (fs.existsSync(guideDir)) {
  for (const f of fs.readdirSync(guideDir).filter((x) => x.endsWith('.txt')).sort()) {
    const id = f.match(/^acord-(\d+)/)?.[1] ?? '';
    const body = fs.readFileSync(path.join(guideDir, f), 'utf8').split('\n').filter((l) => l.trim() && !l.startsWith('#')).join('\n');
    parts.push(`<process_guide form="ACORD ${id}" file="${f}">\n${body}\n</process_guide>`);
  }
}

const out = path.join(here, '..', '..', 'api', '_acord-knowledge.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `// Generated by supabase/knowledge-checks/build-chat-knowledge.mjs — do not edit by hand.
// Automatic (Whisper) transcripts of the LAVA training videos. "Accord" / "a court" / "farm" = ACORD / form.
export const VIDEO_TRANSCRIPTS = ${JSON.stringify(parts.join('\n\n'))};
`);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${parts.length} transcripts and guides)${missing.length ? `; no transcript yet for ${missing.join(', ')}` : ''}`);
